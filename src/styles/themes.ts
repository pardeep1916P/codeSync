export const getSavedThemeId = (): string => {
  if (typeof localStorage !== 'undefined') {
    return localStorage.getItem('codesync_theme') || 'amoled';
  }
  return 'amoled';
};

export const saveThemeId = (themeId: string) => {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('codesync_theme', themeId);
  }
  if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
    chrome.storage.local.set({ themeId });
  }
};
